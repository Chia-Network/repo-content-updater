"""Lock hashes decide whether a pip change is trusted."""

from __future__ import annotations

import hashlib
import unittest
from unittest.mock import patch

import dependency_cursor_review_upstream as upstream
import dependency_update_coverage as coverage
import malware_verdict_formatter as formatter
from test_dependency_update_coverage import _clean, _found, _plan, _run_main

_CHIA = "https://pypi.chia.net/simple/"
_PAGE_URL = f"{_CHIA}chiapos/"
_SDIST = b"chiapos sdist"
_WHEEL = b"chiapos wheel"
_SDIST_URL = "https://download.chia.net/files/chiapos-2.0.4.tar.gz"
_WHEEL_URL = "https://download.chia.net/files/chiapos-2.0.4-cp312-cp312-manylinux_2_28_x86_64.whl"
_PAGE = f'<a href="{_SDIST_URL}">s</a>\n<a href="{_WHEEL_URL}">w</a>\n'.encode()
_CONFIG = "registries:\n  chia:\n    type: python-index\n    url: https://pypi.chia.net/simple/\n"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _pin(*hashes: str) -> str:
    return "chiapos==2.0.4 " + " ".join(f"--hash=sha256:{value}" for value in hashes) + "\n"


def _poetry_lock(*hashes: str, source: str = "") -> str:
    files = ",\n".join(f'    {{file = "chiapos-2.0.4.tar.gz", hash = "sha256:{value}"}}' for value in hashes)
    origin = f'\n[package.source]\ntype = "legacy"\nurl = "{source}"\nreference = "chia"\n' if source else ""
    return (
        "# This file is automatically @generated by Poetry and should not be changed by hand.\n\n"
        '[[package]]\nname = "chiapos"\nversion = "2.0.4"\nfiles = [\n'
        f'{files}\n]\n{origin}\n[metadata]\nlock-version = "2.0"\ncontent-hash = "abc"\n'
    )


class _Response:
    def __init__(self, body: bytes, status: int = 200) -> None:
        self.status = status
        self.body = body

    def getheader(self, _name: str) -> None:
        return None

    def read1(self, size: int = -1) -> bytes:
        if size < 0:
            size = len(self.body)
        chunk, self.body = self.body[:size], self.body[size:]
        return chunk


class _Socket:
    def settimeout(self, _value: float) -> None:
        return None


class _Connection:
    def __init__(self) -> None:
        self.sock = _Socket()

    def close(self) -> None:
        return None


class DependencyUpdateCoverageIndexTest(unittest.TestCase):
    def run_http(
        self,
        texts: dict[str, str],
        hashed: tuple[str, ...],
        *,
        config: str = "",
    ) -> tuple[dict, str, list[str], list[str]]:
        """coverage.main() over one pip change with the trusted index page and both files mocked."""
        looked_up: list[str] = []
        requested: list[str] = []

        def repo(_ecosystem: str, name: str, _version: str) -> upstream.Repo:
            looked_up.append(name)
            return _found(f"upstream/{name}")

        def get_response(url: str, _accept: str, _budget: object = None) -> tuple[_Connection, _Response]:
            requested.append(url)
            answers = {_PAGE_URL: _PAGE, _SDIST_URL: _SDIST, _WHEEL_URL: _WHEEL}
            return _Connection(), _Response(answers.get(url, b""), 200 if url in answers else 404)

        all_texts = {**texts}
        if config:
            all_texts[".github/dependabot.yml"] = config
        plan = _plan(("pip", ".", "chiapos", "2.0.3", "2.0.4"), hashed=hashed)
        with (
            patch.object(coverage, "_git_text", lambda _rev, path: all_texts.get(path, "")),
            patch.object(upstream, "_get_response", get_response),
        ):
            report, summary, _output = _run_main(
                plan, repo=repo, scan=lambda target, *_args: _clean(target.package, target.repo.slug)
            )
        return report, summary, looked_up, requested

    def test_a_hashed_requirements_line_is_trusted_when_the_trusted_index_serves_its_hash(self) -> None:
        report, summary, looked_up, requested = self.run_http(
            {"requirements.txt": _pin(_sha(_SDIST))}, ("requirements.txt",)
        )
        self.assertEqual(looked_up, [])
        self.assertEqual(
            [(item["name"], item["index"]) for item in report["trusted_packages"]], [("chiapos", "pypi.chia.net")]
        )
        self.assertEqual(requested, [_PAGE_URL, _SDIST_URL])
        self.assertIn("lock hashes match files from a trusted index", summary)
        published = formatter.compose_published_review(
            report, "MALWARE_REVIEW_VERDICT: benign\n\nNo issues.\n", "COMPATIBILITY_RECOMMENDATION: Merge\n"
        )
        without = formatter.compose_published_review(
            {**report, "trusted_packages": []},
            "MALWARE_REVIEW_VERDICT: benign\n\nNo issues.\n",
            "COMPATIBILITY_RECOMMENDATION: Merge\n",
        )
        self.assertEqual((published["verdict"], published["check"]), (without["verdict"], without["check"]))

    def test_an_unhashed_occurrence_is_never_trusted_even_beside_a_trusted_index(self) -> None:
        report, _summary, looked_up, requested = self.run_http(
            {"requirements.txt": f"-i {_CHIA}\nchiapos==2.0.4\n"}, ("requirements.txt",), config=_CONFIG
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])
        self.assertEqual(requested, [])

    def test_a_mixed_hashed_and_unhashed_pair_is_scanned(self) -> None:
        report, _summary, looked_up, requested = self.run_http(
            {"requirements.txt": _pin(_sha(_SDIST)), "requirements-dev.txt": "chiapos==2.0.4\n"},
            ("requirements.txt", "requirements-dev.txt"),
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])
        self.assertEqual(requested, [])

    def test_a_hash_the_trusted_index_does_not_serve_is_scanned(self) -> None:
        report, _summary, looked_up, requested = self.run_http(
            {"requirements.txt": _pin(_sha(_SDIST), _sha(b"other"))}, ("requirements.txt",)
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])
        self.assertEqual(requested[:2], [_PAGE_URL, _SDIST_URL])

    def test_a_pypi_only_wheel_hash_is_scanned(self) -> None:
        report, _summary, looked_up, _requested = self.run_http(
            {"requirements.txt": _pin(_sha(b"pypi-only wheel"))}, ("requirements.txt",)
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])

    def test_a_sha512_hash_is_scanned_without_reading_the_index(self) -> None:
        report, _summary, looked_up, requested = self.run_http(
            {"requirements.txt": f"chiapos==2.0.4 --hash=sha512:{_sha(_SDIST)}\n"}, ("requirements.txt",)
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])
        self.assertEqual(requested, [])

    def test_continuation_and_repeated_hash_options_are_read_in_full(self) -> None:
        text = f"chiapos==2.0.4 \\\n    --hash=sha256:{_sha(_SDIST)} \\\n    --hash=sha256:{_sha(_WHEEL)}\n"
        report, _summary, looked_up, requested = self.run_http({"requirements.txt": text}, ("requirements.txt",))
        self.assertEqual(looked_up, [])
        self.assertEqual(
            [(item["name"], item["index"]) for item in report["trusted_packages"]], [("chiapos", "pypi.chia.net")]
        )
        self.assertEqual(requested, [_PAGE_URL, _SDIST_URL, _WHEEL_URL])

    def test_an_unreadable_hash_option_counts_as_unhashed(self) -> None:
        report, _summary, looked_up, requested = self.run_http(
            {"requirements.txt": f'chiapos==2.0.4 --hash=sha256:{_sha(_SDIST)} "\n'}, ("requirements.txt",)
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertEqual(report["trusted_packages"], [])
        self.assertEqual(requested, [])

    def test_a_pyproject_mention_beside_a_hashed_poetry_lock_does_not_block_trust(self) -> None:
        texts = {
            "poetry.lock": _poetry_lock(_sha(_SDIST)),
            "pyproject.toml": '[project]\ndependencies = ["chiapos==2.0.4"]\n',
        }
        report, _summary, looked_up, requested = self.run_http(texts, (), config=_CONFIG)
        self.assertEqual(looked_up, [])
        self.assertEqual(
            [(item["name"], item["index"]) for item in report["trusted_packages"]], [("chiapos", "pypi.chia.net")]
        )
        self.assertEqual(requested, [_PAGE_URL, _SDIST_URL])

    def test_a_hashed_poetry_lock_package_from_another_source_is_trusted_when_the_trusted_index_serves_its_hash(
        self,
    ) -> None:
        texts = {
            "poetry.lock": _poetry_lock(_sha(_SDIST), source="https://pypi.chia.net/simple"),
            "pyproject.toml": '[project]\ndependencies = ["chiapos==2.0.4"]\n',
        }
        report, _summary, looked_up, requested = self.run_http(texts, (), config=_CONFIG)
        self.assertEqual(looked_up, [])
        self.assertEqual(
            [(item["name"], item["index"]) for item in report["trusted_packages"]], [("chiapos", "pypi.chia.net")]
        )
        self.assertEqual(requested, [_PAGE_URL, _SDIST_URL])

    def test_an_untrusted_requirements_index_does_not_make_the_change_inconclusive(self) -> None:
        report, summary, looked_up, _requested = self.run_http(
            {"requirements.txt": "--index-url https://example.com/simple/\nchiapos==2.0.4\n"},
            ("requirements.txt",),
        )
        self.assertEqual(looked_up, ["chiapos"])
        self.assertNotIn("configured_index", summary)
        self.assertEqual(report["trusted_packages"], [])


if __name__ == "__main__":
    unittest.main()
